"""Alert rules: one definition, rendered for Prometheus and evaluated locally (ADR-072).

``ALERT_RULES`` is the single source of truth. ``render_prometheus_rules``
writes ``deploy/service/alerts.yml`` (a test keeps the file identical), and
``AlertEvaluator`` applies the same rules to sampled ``ServiceMetrics``
snapshots, so firing and clearing behaviour is tested without a Prometheus
server. Availability alerts follow the multi-window, multi-burn-rate pattern:
a page needs both the long and the short window to burn the error budget at
the page rate; a ticket uses the slower pair.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Mapping, Optional, Sequence

from src.service.metrics import SLO, load_slo


@dataclass(frozen=True)
class AlertRule:
    name: str
    severity: str
    kind: str  # burn | slow_ratio | not_ready | increase
    for_s: int
    summary: str
    long_s: int = 0
    short_s: int = 0
    factor: float = 0.0
    counter: str = ""
    threshold: float = 0.0


def alert_rules(slo: SLO) -> List[AlertRule]:
    return [
        AlertRule("AifinAvailabilityBudgetBurnFast", "page", "burn", 120,
                  "Availability error budget burning fast (1h and 5m windows)", 3600, 300, slo.page_burn_rate),
        AlertRule("AifinAvailabilityBudgetBurnSlow", "ticket", "burn", 900,
                  "Availability error budget burning (6h and 30m windows)", 21600, 1800, slo.ticket_burn_rate),
        AlertRule("AifinAnswerLatencySLO", "ticket", "slow_ratio", 600,
                  "Too many answers slower than the latency SLO threshold", 1800, 300,
                  threshold=2 * (1 - slo.latency_target)),
        AlertRule("AifinNotReady", "page", "not_ready", 60, "Serving release is not ready"),
        AlertRule("AifinOverloaded", "ticket", "increase", 300, "Admission control is rejecting requests",
                  long_s=300, counter="rejected_overload", threshold=0),
        AlertRule("AifinSandboxSecurityEvent", "ticket", "increase", 0,
                  "Generated code attempted a denied sandbox capability", long_s=300, counter="security_events",
                  threshold=0),
    ]


_PROM_COUNTER = {"rejected_overload": "aifin_overload_rejections_total",
                 "security_events": "aifin_sandbox_security_events_total"}


def _window(seconds: int) -> str:
    return f"{seconds // 3600}h" if seconds % 3600 == 0 else f"{seconds // 60}m"


def _expr(rule: AlertRule, slo: SLO) -> str:
    if rule.kind == "burn":
        def ratio(seconds):
            w = _window(seconds)
            return (f'(sum(increase(aifin_slo_events_total{{kind="bad"}}[{w}])) / '
                    f'sum(increase(aifin_slo_events_total{{kind="total"}}[{w}])))')
        limit = round(rule.factor * slo.error_budget, 6)
        return f"{ratio(rule.long_s)} > {limit}\nand\n{ratio(rule.short_s)} > {limit}"
    if rule.kind == "slow_ratio":
        def ratio(seconds):
            w = _window(seconds)
            return f"(increase(aifin_answer_slow_total[{w}]) / increase(aifin_answered_total[{w}]))"
        return f"{ratio(rule.long_s)} > {rule.threshold:g}\nand\n{ratio(rule.short_s)} > {rule.threshold:g}"
    if rule.kind == "not_ready":
        return "aifin_ready == 0"
    return f"increase({_PROM_COUNTER[rule.counter]}[{_window(rule.long_s)}]) > {rule.threshold:g}"


def render_prometheus_rules(slo: Optional[SLO] = None) -> str:
    slo = slo or load_slo()
    lines = ["# Generated by src/service/alerting.py from deploy/service/slo.toml; do not edit by hand.",
             "groups:", "  - name: aifin-service", "    rules:"]
    for rule in alert_rules(slo):
        lines += [f"      - alert: {rule.name}", "        expr: |"]
        lines += [f"          {line}" for line in _expr(rule, slo).splitlines()]
        lines += [f"        for: {rule.for_s}s", "        labels:", f"          severity: {rule.severity}",
                  "        annotations:", f"          summary: \"{rule.summary}\""]
    return "\n".join(lines) + "\n"


class AlertEvaluator:
    """Evaluate the rules over a time-ordered list of metric snapshots."""

    def __init__(self, slo: Optional[SLO] = None) -> None:
        self.slo = slo or load_slo()
        self.rules = alert_rules(self.slo)
        self._pending: Dict[str, float] = {}

    @staticmethod
    def _increase(samples: Sequence[Mapping[str, float]], key: str, seconds: int) -> float:
        now = samples[-1]["t"]
        start = next((sample for sample in samples if sample["t"] >= now - seconds), samples[0])
        return max(0.0, samples[-1][key] - start[key])

    def _condition(self, rule: AlertRule, samples: Sequence[Mapping[str, float]]) -> bool:
        if rule.kind == "burn":
            limit = rule.factor * self.slo.error_budget
            for seconds in (rule.long_s, rule.short_s):
                total = self._increase(samples, "total", seconds)
                if total <= 0 or self._increase(samples, "bad", seconds) / total <= limit:
                    return False
            return True
        if rule.kind == "slow_ratio":
            for seconds in (rule.long_s, rule.short_s):
                answered = self._increase(samples, "answered", seconds)
                if answered <= 0 or self._increase(samples, "slow_answers", seconds) / answered <= rule.threshold:
                    return False
            return True
        if rule.kind == "not_ready":
            return samples[-1]["ready"] == 0
        return self._increase(samples, rule.counter, rule.long_s) > rule.threshold

    def evaluate(self, samples: Sequence[Mapping[str, float]]) -> List[str]:
        """Names of the alerts firing at the last sample (conditions held for ``for``)."""
        now = samples[-1]["t"]
        firing = []
        for rule in self.rules:
            if self._condition(rule, samples):
                since = self._pending.setdefault(rule.name, now)
                if now - since >= rule.for_s:
                    firing.append(rule.name)
            else:
                self._pending.pop(rule.name, None)
        return firing
